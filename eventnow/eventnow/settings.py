# --- Media storage: Cloudinary --------------------------------------------
# User-uploaded media (event banners, session images via ImageField) can't
# live on Render's filesystem — the free tier has no persistent disk, so
# uploads would vanish on every redeploy. Cloudinary provides free-tier
# object storage plus a CDN with automatic image optimisation.
# django-cloudinary-storage swaps Django's default file storage backend
# so ImageField.save() uploads to Cloudinary transparently, and the URL
# returned by image.url points to Cloudinary's CDN.
